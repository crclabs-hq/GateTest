describe('buildTable', () => {
  const table = buildTable(fixture());

  it('has one column per tool, bad columns included', () => {
    assert.deepStrictEqual(table.columns.map((c) => c.key), ['gatetest', 'semgrep', 'eslintSecurity', 'sonarqube', 'codeql']);
    assert.deepStrictEqual(table.columns.map((c) => c.version), ['1.61.1', null, null, null, null]);
  });

  it('never renders a blank cell, whatever the tool did', () => {
    for (const row of table.rows) {
      assert.strictEqual(row.cells.length, 5, `${row.name} has a cell per column`);
      for (const cell of row.cells) {
        assert.strictEqual(typeof cell.text, 'string');
        assert.ok(cell.text.trim().length > 0, `${row.name}: blank cell`);
        assert.ok(cell.kind, `${row.name}: cell has a kind`);
      }
    }
  });

  it('says what happened in the non-ok cells', () => {
    const [express, django, gin] = table.rows;
    assert.match(express.cells[0].text, /^0 blocking \/ 13 findings$/);
    assert.strictEqual(express.cells[0].detail, '41.2 s');
    assert.strictEqual(express.cells[0].kind, 'clean');
    assert.strictEqual(express.cells[1].text, 'tool unavailable on this runner');
    assert.match(express.cells[2].text, /^timed out after 600\.0 s$/);
    assert.match(django.cells[0].text, /^timed out after 600\.0 s$/);
    assert.match(django.cells[1].text, /^3 error \/ 40 warning \/ 2 info$/);
    assert.match(django.cells[2].text, /^not run — not a JavaScript\/TypeScript repository$/);
    assert.match(gin.cells[0].text, /^failed \(exit 3\)$/);
    assert.match(gin.cells[1].text, /^failed \(exit 2\)/);
  });

  it('renders SonarQube as not measured for every repo, with the document reason', () => {
    for (const row of table.rows) {
      assert.match(row.cells[3].text, /^not measured — needs a server$/);
    }
  });

  it('renders CodeQL per repo: measured when the adapter ran, not-measured with the reason when it could not, and generically not-measured for a row from before the column existed', () => {
    const [express, django, gin] = table.rows;
    assert.match(express.cells[4].text, /^2 blocking-equivalent \/ 9 results$/);
    assert.strictEqual(express.cells[4].detail, '88.4 s');
    assert.strictEqual(express.cells[4].kind, 'measured');
    assert.match(django.cells[4].text, /^not measured — codeql database create failed \(exit 1\)/);
    assert.strictEqual(django.cells[4].kind, 'not-measured');
    assert.strictEqual(gin.cells[4].text, STATUS.notMeasured, 'a row with no codeql key at all still says something, never blank');
    assert.strictEqual(gin.cells[4].kind, 'not-measured');
  });

  it('survives a document with nothing in it rather than throwing on the page', () => {
    const empty = buildTable({});
    assert.strictEqual(empty.rows.length, 0);
    assert.strictEqual(empty.columns.length, 5);
    const nulls = buildTable({ repos: [{ name: 'x', url: 'u', sha: SHA, gatetest: null, semgrep: undefined }] });
    for (const cell of nulls.rows[0].cells) assert.ok(cell.text.trim().length > 0, 'null tools still say something');
    assert.strictEqual(nulls.rows[0].language, 'unknown');
  });
});

