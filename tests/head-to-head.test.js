// =============================================================================
// Head-to-head — the published comparison table is generated, validated, and
// never renders a blank cell
// =============================================================================
// scripts/head-to-head.js measures GateTest, Semgrep and ESLint
// (eslint-plugin-security) on the pinned corpus and writes
// website/app/data/head-to-head.json; /precision renders it through
// website/app/lib/head-to-head.js — the one definition both sides import.
// This file is the control pair for that module, the committed JSON, the
// page's use of it, and the weekly workflow:
//
//   - the validator accepts the committed file and rejects every shape that
//     would render as a blank or as a number nobody measured
//   - the run-order and time-box helpers do what the script relies on
//   - buildTable never yields an empty cell — a tool that was not run, timed
//     out, was unavailable, or is not measured yet SAYS SO in the cell
//   - the committed JSON pins the same commits the corpus manifest pins and
//     never claims more repos than the corpus has
//   - the page imports the JSON and the table builder and types no count
//   - the workflow installs Semgrep with pip on ubuntu and runs the script
// =============================================================================

