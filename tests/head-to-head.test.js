describe('validateHeadToHead', () => {
  it('accepts a document with every kind of null and non-ok status', () => {
    assert.deepStrictEqual(validateHeadToHead(fixture()), []);
  });

  it('rejects a document that is not generated by the script', () => {
    const problems = validateHeadToHead(fixture({ source: 'typed by hand' }));
    assert.ok(problems.some((p) => /source/.test(p)), problems.join('\n'));
  });

  it('rejects an ok GateTest cell without its numbers', () => {
    const doc = fixture();
    doc.repos[0].gatetest = { status: 'ok', seconds: 1 };
    const problems = validateHeadToHead(doc);
    assert.ok(problems.some((p) => /gatetest\.blocking/.test(p)));
    assert.ok(problems.some((p) => /gatetest\.total/.test(p)));
  });

  it('rejects blocking above total', () => {
    const doc = fixture();
    doc.repos[0].gatetest = { status: 'ok', blocking: 5, total: 2, seconds: 1 };
    assert.ok(validateHeadToHead(doc).some((p) => /blocking exceeds total/.test(p)));
  });

  it('rejects an ok Semgrep cell without severities or an exit status', () => {
    const doc = fixture();
    doc.repos[1].semgrep = { status: 'ok', seconds: 1 };
    const problems = validateHeadToHead(doc);
    for (const k of ['error', 'warning', 'info', 'exit']) {
      assert.ok(problems.some((p) => new RegExp(`semgrep\\.${k}`).test(p)), `expected a problem about semgrep.${k}`);
    }
  });

  it('rejects a blank status — the thing that would render as an empty cell', () => {
    const doc = fixture();
    doc.repos[0].semgrep = { status: '', seconds: 0 };
    assert.ok(validateHeadToHead(doc).some((p) => /semgrep\.status/.test(p)));
  });

  it('rejects a missing eslintSecurity key (null is the explicit "not a JS/TS repo")', () => {
    const doc = fixture();
    delete doc.repos[1].eslintSecurity;
    assert.ok(validateHeadToHead(doc).some((p) => /eslintSecurity must be present/.test(p)));
  });

  it('refuses a SonarQube or CodeQL number nobody measured', () => {
    const doc = fixture();
    doc.tools.sonarqube = { status: 'ok', findings: 12 };
    const problems = validateHeadToHead(doc);
    assert.ok(problems.some((p) => /tools\.sonarqube\.status/.test(p)));
    assert.ok(problems.some((p) => /tools\.sonarqube\.reason/.test(p)));
  });

  it('requires a reason when a tool has no version', () => {
    const doc = fixture();
    doc.tools.semgrep = { version: null };
    assert.ok(validateHeadToHead(doc).some((p) => /tools\.semgrep: a null version needs a reason/.test(p)));
  });

  it('rejects duplicate repos and short shas', () => {
    const doc = fixture();
    doc.repos.push({ ...doc.repos[0], sha: 'abc123' });
    const problems = validateHeadToHead(doc);
    assert.ok(problems.some((p) => /duplicate repo/.test(p)));
    assert.ok(problems.some((p) => /sha must be a full 40-hex commit/.test(p)));
  });

  it('rejects an empty corpus', () => {
    assert.ok(validateHeadToHead(fixture({ repos: [] })).some((p) => /repos must not be empty/.test(p)));
    assert.deepStrictEqual(validateHeadToHead(null), ['document must be an object']);
  });

  // -------------------------------------------------------------------------
  // CodeQL — measured per repo now, but a document from before the adapter
  // existed (no per-repo codeql key, or the old document-level
  // {status:'not measured', reason} shape) must keep validating.
  // -------------------------------------------------------------------------

  it('accepts the versioned tools.codeql shape once the CLI has actually run', () => {
    const doc = fixture();
    doc.tools.codeql = { version: '2.27.0', command: 'codeql database create ...' };
    assert.deepStrictEqual(validateHeadToHead(doc), []);
  });

  it('rejects an empty tools.codeql entry (neither versioned nor the pre-adapter shape)', () => {
    const doc = fixture();
    doc.tools.codeql = {};
    assert.ok(validateHeadToHead(doc).some((p) => /tools\.codeql\.version must be a string or null/.test(p)));
  });

  it('rejects a versioned tools.codeql with a null version and no reason', () => {
    const doc = fixture();
    doc.tools.codeql = { version: null };
    assert.ok(validateHeadToHead(doc).some((p) => /tools\.codeql: a null version needs a reason/.test(p)));
  });

  it('rejects an ok codeql row missing its blocking-equivalent/total counts', () => {
    const doc = fixture();
    doc.repos[0].codeql = { status: 'ok', seconds: 1 };
    const problems = validateHeadToHead(doc);
    assert.ok(problems.some((p) => /codeql\.blocking must be an integer/.test(p)));
    assert.ok(problems.some((p) => /codeql\.total must be an integer/.test(p)));
  });

  it('rejects codeql blocking above total, the same rule gatetest gets', () => {
    const doc = fixture();
    doc.repos[0].codeql = { status: 'ok', blocking: 5, total: 2, seconds: 1 };
    assert.ok(validateHeadToHead(doc).some((p) => /codeql: blocking exceeds total/.test(p)));
  });

  it('rejects a not-measured codeql row without a reason — never a silent zero', () => {
    const doc = fixture();
    doc.repos[0].codeql = { status: 'not measured', seconds: 1 };
    assert.ok(validateHeadToHead(doc).some((p) => /codeql: a not-measured result needs a reason/.test(p)));
  });

  it('accepts codeql: null on a repo (explicitly skipped) and a repo with no codeql key at all', () => {
    const doc = fixture();
    doc.repos[0].codeql = null;
    delete doc.repos[1].codeql;
    assert.deepStrictEqual(validateHeadToHead(doc), []);
  });
});

