describe('run order and limits', () => {
  const manifest = ['express', 'flask', 'fastify', 'got', 'hono', 'zod', 'django', 'rails', 'gin', 'laravel', 'NodeGoat'].map((name) => ({ name }));

  it('orderRepos puts the priority list first, then the manifest order', () => {
    const names = orderRepos(manifest).map((r) => r.name);
    assert.deepStrictEqual(names, ['express', 'django', 'rails', 'flask', 'fastify', 'zod', 'gin', 'laravel', 'got', 'hono', 'NodeGoat']);
  });

  it('orderRepos ignores priority names the manifest lacks and keeps every repo once', () => {
    const names = orderRepos(manifest, ['nope', 'gin', 'express']).map((r) => r.name);
    assert.strictEqual(names.length, manifest.length);
    assert.deepStrictEqual(names.slice(0, 2), ['gin', 'express']);
    assert.strictEqual(new Set(names).size, names.length);
  });

  it('limitRepos cuts after ordering; a missing or non-positive limit means all', () => {
    assert.deepStrictEqual(limitRepos(manifest, 3).map((r) => r.name), ['express', 'django', 'rails']);
    assert.strictEqual(limitRepos(manifest, null).length, manifest.length);
    assert.strictEqual(limitRepos(manifest, 0).length, manifest.length);
    assert.strictEqual(limitRepos(manifest, 99).length, manifest.length);
  });

  it('the time box is ten minutes per tool per repo', () => {
    assert.strictEqual(TOOL_TIMEOUT_MS, 10 * 60 * 1000);
  });

  it('elapsedSeconds reads an hrtime.bigint() start to one decimal', () => {
    const start = 1_000_000_000n;
    assert.strictEqual(elapsedSeconds(start, start + 41_250_000_000n), 41.3);
    assert.strictEqual(elapsedSeconds(start, start), 0);
    assert.ok(elapsedSeconds(process.hrtime.bigint()) < 1);
  });

  it('parseArgs understands the documented flags and rejects the rest', () => {
    const o = script.parseArgs(['--repos', '8', '--json', '--suite', 'quick', '--merge', '--no-eslint', '--timeout-minutes', '2']);
    assert.strictEqual(o.repos, 8);
    assert.strictEqual(o.json, true);
    assert.strictEqual(o.suite, 'quick');
    assert.strictEqual(o.merge, true);
    assert.strictEqual(o.eslint, false);
    assert.strictEqual(o.timeoutMs, 120000);
    assert.strictEqual(script.parseArgs([]).suite, 'full', 'the default suite is the one the corpus gate runs');
    assert.strictEqual(script.parseArgs([]).timeoutMs, TOOL_TIMEOUT_MS);
    assert.throws(() => script.parseArgs(['--repos', '0']), /positive integer/);
    assert.throws(() => script.parseArgs(['--bogus']), /unknown argument/);
  });
});

